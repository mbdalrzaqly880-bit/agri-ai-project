# توصية عامة "احتياطية" تُستخدم لو نوع الفاكهة المكتشف مو موجود
# بالقاموس فوق (عشان الكود ما ينهار أبداً حتى لو ظهر نوع فاكهة جديد)
DEFAULT_TREATMENT = (
    "يُنصح بإزالة الثمرة المصابة فوراً لتجنّب انتقال الفساد لبقية "
    "المحصول، واستشارة مهندس زراعي مختص لتحديد السبب الدقيق ومعالجته."
)


def get_treatment(fruit_type_english):
    """
    ترجع توصية العلاج المناسبة حسب نوع الفاكهة.

    المعامل (Parameter):
    - fruit_type_english: اسم نوع الفاكهة بالإنجليزي وبأحرف صغيرة
      (مثال: "mango", "banana") - نفس الاسم اللي يطلعه الموديل

    ترجع: نص التوصية (string)
    """
    # .get(key, default) تبحث عن المفتاح بالقاموس، ولو ما لقته ترجع
    # القيمة الاحتياطية (DEFAULT_TREATMENT) بدل ما يصير خطأ بالبرنامج
    return TREATMENT_RECOMMENDATIONS.get(
        fruit_type_english.lower(),
        DEFAULT_TREATMENT
    )
