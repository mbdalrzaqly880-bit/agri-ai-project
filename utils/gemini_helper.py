import os
import requests  # مكتبة نستخدمها لإرسال طلبات HTTP لأي API خارجي

# ------------------------------------------------------------------------------
# مفتاح الـ API - نقرأه من "متغير بيئة" (Environment Variable) وليس مكتوب
# بالكود مباشرة. هذا مبدأ أمان مهم جداً: لو كتبنا المفتاح داخل الكود ورفعنا
# المشروع على GitHub، أي شخص يقدر يشوف المفتاح ويستخدمه على حسابك
# ------------------------------------------------------------------------------
GEMINI_API_KEY = os.environ.get('GEMINI_API_KEY')

# رابط الـ API الرسمي من جوجل - نستخدم "gemini-flash-latest" لأنه
# الاسم المؤكد نجاحه مع حسابات المستخدمين الجدد (بعض أسماء الإصدارات
# المحددة مثل gemini-2.5-flash انسحبت من الحسابات الجديدة، بينما هذا
# الاسم "المستعار" يوجّه تلقائياً لأحدث نسخة Flash متاحة فعلياً)
GEMINI_URL = (
    "https://generativelanguage.googleapis.com/v1beta/models/"
    "gemini-flash-latest:generateContent"
)

# ------------------------------------------------------------------------------
# تعليمات النظام (System Instruction): نص ثابت نرسله مع كل طلب يخبر
# الموديل "كيف يتصرف". هنا نخليه متخصص بالزراعة فقط، وبيقول ما يعرف
# لو السؤال برا تخصصه، بدل ما يجاوب بمعلومات عامة قد تكون غير دقيقة
# ------------------------------------------------------------------------------
SYSTEM_INSTRUCTION = (
    "أنت خبير زراعي متخصص تساعد المزارعين في اليمن والمنطقة العربية. "
    "أجب على أسئلة الزراعة والنباتات والفواكه والأمراض الزراعية بشكل "
    "عملي ومختصر وواضح باللغة العربية. لو سُئلت عن شيء خارج تخصص "
    "الزراعة، اعتذر بلطف ووضّح أنك متخصص بالمجال الزراعي فقط."
)


def ask_gemini(user_message, conversation_history=None):
    """
    ترسل رسالة المستخدم لـ Gemini API وترجع رد الذكاء الاصطناعي كنص.

    المعاملات (Parameters):
    - user_message: نص السؤال اللي كتبه المزارع
    - conversation_history: قائمة فيها الرسائل السابقة بالمحادثة (اختياري)
      نمررها عشان الموديل "يتذكر" سياق المحادثة، مو يجاوب كل سؤال لحاله
      بدون معرفة اللي قبله

    ترجع: نص الرد (string)، أو رسالة خطأ واضحة لو صار مشكلة
    """

    # لو ما فيه مفتاح API أصلاً، نوقف فوراً برسالة واضحة بدل خطأ غامض
    if not GEMINI_API_KEY:
        return (
            "لم يتم إعداد مفتاح Gemini API بعد. تأكد من إضافة "
            "GEMINI_API_KEY في ملف .env"
        )

    # نبني قائمة الرسائل بالصيغة اللي يطلبها Gemini API بالضبط:
    # كل رسالة فيها "role" (المتحدث: user أو model) و"parts" (النص نفسه)
    contents = []

    # لو فيه محادثة سابقة، نضيفها أول شي عشان يكون عند الموديل سياق كامل
    if conversation_history:
        for msg in conversation_history:
            contents.append({
                "role": msg["role"],
                "parts": [{"text": msg["text"]}]
            })

    # نضيف رسالة المستخدم الحالية بآخر القائمة
    contents.append({
        "role": "user",
        "parts": [{"text": user_message}]
    })

    # جسم الطلب (Request Body) اللي بنرسله للـ API
    payload = {
        "system_instruction": {
            "parts": [{"text": SYSTEM_INSTRUCTION}]
        },
        "contents": contents
    }

    # الترويسات (Headers) - نرسل بس نوع المحتوى هنا
    headers = {
        "Content-Type": "application/json"
    }

    # نرسل المفتاح كـ query parameter بالرابط نفسه (?key=...) بدل الـ header
    # هذي الطريقة أثبتنا نجاحها بالاختبار المباشر، فنعتمدها لضمان التوافق
    request_url = f"{GEMINI_URL}?key={GEMINI_API_KEY}"

    try:
        # نرسل الطلب فعلياً - timeout=20 يعني "لو ما رد خلال 20 ثانية، أوقف
        # ولا تعلّق الموقع للأبد" (مهم جداً مع إنترنت ضعيف)
        response = requests.post(request_url, headers=headers, json=payload, timeout=20)

        # لو الرد رجع كود خطأ (مثل 400 أو 403)، نرمي استثناء يدخلنا للـ except
        response.raise_for_status()

        # نحوّل رد السيرفر من JSON لقاموس بايثون عادي
        data = response.json()

        # نستخرج النص الفعلي من داخل هيكلة رد Gemini (قد تبان معقدة، لكنها
        # ثابتة الشكل: candidates -> أول عنصر -> content -> parts -> أول نص)
        reply_text = data["candidates"][0]["content"]["parts"][0]["text"]
        return reply_text

    except requests.exceptions.Timeout:
        return "انتهت مهلة الاتصال بالخادم. تأكد من اتصالك بالإنترنت وحاول مرة أخرى."

    except requests.exceptions.RequestException as e:
        # أي خطأ ثاني بالاتصال (مفتاح خطأ، مشكلة شبكة، إلخ)
        return f"حدث خطأ أثناء التواصل مع خدمة الذكاء الاصطناعي: {str(e)}"

    except (KeyError, IndexError):
        # لو رجع رد لكن بشكل غير متوقع (هيكلة مختلفة عن المتوقع)
        return "تم استلام رد غير متوقع من الخادم. حاول مرة أخرى."
